"""Tables (Markdown + CSV) and figures from the saved result files."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

# Published numbers, kept separate from anything measured here.
PAPER_TABLE4_ESC50_ZS = {  # Wu et al., ICASSP 2023, arXiv:2211.06687 v4, Table 4 (ESC-50 zero-shot, %)
    "CLAP": 89.1, "CLAP+Fusion": 88.0, "CLAP+K2C Aug.": 91.0,
    "Microsoft CLAP (Elizalde et al.)": 82.6, "AudioCLIP": 69.4, "Wav2CLIP": 41.4,
}
README_FOLD1_R1 = {  # LAION-AI/CLAP README, "Zeroshot Classification with ESC50 official split" (fold 1)
    "630k-audioset-best": 92.75, "630k-audioset-fusion-best": 90.50,
}

METHOD_ORDER = ["zero-shot", "tip-clean", "tip-aug", "tip-noisy-only", "lp-clean", "lp-aug"]


def _t_ci(x: np.ndarray, conf: float = 0.95):
    from scipy import stats

    x = np.asarray(x, dtype=float)
    n = len(x)
    m = x.mean()
    if n < 2:
        return m, np.nan, np.nan
    h = stats.t.ppf(0.5 + conf / 2, n - 1) * x.std(ddof=1) / np.sqrt(n)
    return m, m - h, m + h


def summarize(runs: pd.DataFrame) -> pd.DataFrame:
    g = runs.groupby(["method", "k", "condition"])["acc"]
    s = g.agg(["mean", "std", "count"]).reset_index()
    s[["mean", "std"]] *= 100
    return s


def noise_group(cond: str) -> str:
    return "clean" if cond == "clean" else cond.split("_")[0]


def paired_diffs(runs: pd.DataFrame, pairs) -> pd.DataFrame:
    """Per-run differences (same fold, seed, k, condition) with a t-based 95% CI.

    Zero-shot has no seed/k, so it is matched on fold only.
    """
    rows = []
    for a, b in pairs:
        ra = runs[runs.method == a]
        rb = runs[runs.method == b]
        if b == "zero-shot":
            rb = rb[["test_fold", "condition", "acc"]]
            m = ra.merge(rb, on=["test_fold", "condition"], suffixes=("_a", "_b"))
        else:
            m = ra.merge(rb, on=["test_fold", "seed", "k", "condition"], suffixes=("_a", "_b"))
        m["group"] = m["condition"].map(noise_group)
        for (k, grp), sub in m.groupby(["k", "group"]):
            # average over SNRs inside a run first, so each run counts once
            per_run = sub.groupby(["test_fold", "seed"])[["acc_a", "acc_b"]].mean()
            d = (per_run["acc_a"] - per_run["acc_b"]).to_numpy() * 100
            mean, lo, hi = _t_ci(d)
            rows.append(dict(comparison=f"{a} - {b}", k=k, noise=grp, mean_diff_pp=mean,
                             ci95_lo=lo, ci95_hi=hi, n_runs=len(d), runs_better=int((d > 0).sum()),
                             runs_worse=int((d < 0).sum())))
    return pd.DataFrame(rows)


def _md(df: pd.DataFrame, floatfmt="{:.2f}") -> str:
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def run_report_stage(cfg, meta):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    out = Path(cfg["results_dir"])
    fig_dir = out / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    names = meta.drop_duplicates("label").sort_values("label")["class_name"].tolist()
    md = ["# Results (generated by `python run_all.py --stage report`)\n",
          "All numbers in this file were measured in this repository unless the column says *paper* or *README*.\n"]

    # ---------------- reproduction
    rep = pd.read_csv(out / "reproduction.csv")
    t1 = rep[["checkpoint", "template", "acc_all", "acc_fold_mean", "acc_fold_std", "fold1_R@1", "fold1_R@5"]].copy()
    for c in ["acc_all", "acc_fold_mean", "acc_fold_std", "fold1_R@1", "fold1_R@5"]:
        t1[c] *= 100
    t1["README fold-1 R@1"] = t1.apply(
        lambda r: README_FOLD1_R1.get(r.checkpoint, np.nan) if r.template == "This is a sound of {}." else np.nan, axis=1)
    t1.to_csv(out / "table1_reproduction.csv", index=False)
    md += ["## Table 1. Zero-shot ESC-50 reproduction (measured, %)\n", _md(t1), "",
           "Published ESC-50 zero-shot accuracy (paper Table 4, %, not measured here): " +
           ", ".join(f"{k} {v}" for k, v in PAPER_TABLE4_ESC50_ZS.items()) + ".\n"]

    # ---------------- few-shot summary
    runs = pd.read_csv(out / "fewshot_runs.csv")
    s = summarize(runs)
    s.to_csv(out / "summary_fewshot.csv", index=False)
    conds = list(dict.fromkeys(runs["condition"]))
    for k in sorted(runs.loc[runs.k > 0, "k"].unique()):
        sub = s[(s.k == k) | (s.method == "zero-shot")]
        piv = sub.pivot_table(index="method", columns="condition", values="mean").reindex(
            [m for m in METHOD_ORDER if m in sub.method.unique()])[conds]
        piv.insert(1, "noisy avg", piv[[c for c in conds if c != "clean"]].mean(axis=1))
        piv = piv.reset_index()
        piv.to_csv(out / f"table2_k{k}.csv", index=False)
        md += [f"## Table 2 (K={k}). Accuracy (%) by condition, mean over 5 test folds x {runs.seed.max() + 1} seeds "
               f"(zero-shot: mean over 5 folds)\n", _md(piv, "{:.1f}"), ""]

    # std table for the largest K
    kmax = int(runs.k.max())
    sd = s[(s.k == kmax) | (s.method == "zero-shot")].pivot_table(index="method", columns="condition", values="std")
    sd = sd.reindex([m for m in METHOD_ORDER if m in sd.index])[conds].reset_index()
    md += [f"Standard deviation across runs (K={kmax}, pp):\n", _md(sd, "{:.1f}"), ""]

    # ---------------- paired comparisons
    pairs = [("tip-aug", "tip-clean"), ("tip-clean", "zero-shot"), ("tip-aug", "zero-shot"),
             ("lp-aug", "lp-clean"), ("tip-aug", "lp-aug"), ("tip-noisy-only", "tip-clean")]
    pdf = paired_diffs(runs, pairs)
    pdf.to_csv(out / "table3_paired.csv", index=False)
    md += ["## Table 3. Paired differences (pp), averaged over SNRs within each run, 95% t-CI over runs\n",
           "Runs share fold, seed and support set, so the CI reflects variation over 15 (fold, seed) runs; "
           "folds are not independent samples, so treat the interval as approximate.\n",
           _md(pdf), ""]

    # ---------------- resources
    enc_path = out / "resources_encoder.json"
    if enc_path.exists():
        enc = json.loads(enc_path.read_text())
        md += ["## Table 4a. Audio encoder cost (measured)\n", "```", json.dumps(enc, indent=2), "```", ""]
    ad = pd.read_csv(out / "resources_adapters.csv")
    md += ["## Table 4b. Adapter cost on top of the encoder (CPU, numpy/sklearn, measured)\n", _md(ad, "{:.4f}"), ""]

    # ---------------- failure analysis
    pred = pd.read_csv(out / f"predictions_k{kmax}_seed0.csv")
    y = pred["label"].to_numpy()
    zs_cols = [c for c in pred.columns if c.startswith("zero-shot|")]
    worst_cond = {g: f"{g}_0dB" for g in ["white", "pink", "brown"] if f"zero-shot|{g}_0dB" in pred.columns}
    pc = pd.DataFrame({"class": names})
    pc["zs_clean"] = [np.mean(pred["zero-shot|clean"].to_numpy()[y == c] == c) * 100 for c in range(len(names))]
    for g, cond in worst_cond.items():
        pc[f"zs_{cond}"] = [np.mean(pred[f"zero-shot|{cond}"].to_numpy()[y == c] == c) * 100 for c in range(len(names))]
    noisy_cols = [c for c in zs_cols if not c.endswith("|clean")]
    pc["zs_noisy_avg"] = [np.mean(np.stack([pred[c].to_numpy()[y == k] == k for c in noisy_cols])) * 100
                          for k in range(len(names))]
    pc["drop_pp"] = pc["zs_clean"] - pc["zs_noisy_avg"]
    for m in ["tip-clean", "tip-aug"]:
        cols = [f"{m}|{c.split('|')[1]}" for c in noisy_cols if f"{m}|{c.split('|')[1]}" in pred.columns]
        if cols:
            pc[f"{m}_noisy_avg"] = [np.mean(np.stack([pred[c].to_numpy()[y == k] == k for c in cols])) * 100
                                    for k in range(len(names))]
    if "tip-aug_noisy_avg" in pc and "tip-clean_noisy_avg" in pc:
        pc["aug_gain_pp"] = pc["tip-aug_noisy_avg"] - pc["tip-clean_noisy_avg"]
    pc.to_csv(out / "per_class.csv", index=False)
    md += [f"## Table 5. Classes most hurt by noise (zero-shot, average over all noisy conditions)\n",
           _md(pc.sort_values("drop_pp", ascending=False).head(10), "{:.1f}"), ""]
    if "aug_gain_pp" in pc:
        md += [f"## Table 6. Per-class effect of the noisy cache (tip-aug - tip-clean, K={kmax}, seed 0, noisy avg)\n",
               "Largest gains:\n", _md(pc.sort_values("aug_gain_pp", ascending=False).head(8)[
                   ["class", "tip-clean_noisy_avg", "tip-aug_noisy_avg", "aug_gain_pp"]], "{:.1f}"), "",
               "Largest losses (unfavourable cases):\n", _md(pc.sort_values("aug_gain_pp").head(8)[
                   ["class", "tip-clean_noisy_avg", "tip-aug_noisy_avg", "aug_gain_pp"]], "{:.1f}"), ""]

    # prediction collapse: which classes absorb predictions under heavy noise
    collapse = []
    for g, cond in worst_cond.items():
        for m in ["zero-shot", "tip-aug"]:
            col = f"{m}|{cond}"
            if col not in pred:
                continue
            vc = pd.Series(pred[col]).value_counts()
            top = vc.head(3)
            collapse.append(dict(method=m, condition=cond,
                                 top_predicted=", ".join(f"{names[i]} ({n})" for i, n in top.items()),
                                 share_top3_pct=100 * top.sum() / len(pred)))
    cdf = pd.DataFrame(collapse)
    cdf.to_csv(out / "table7_collapse.csv", index=False)
    md += ["## Table 7. Prediction collapse at 0 dB (counts out of 2000 clips)\n", _md(cdf, "{:.1f}"), ""]

    (out / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")

    # ---------------- figures
    snr_conds = [c for c in conds if c != "clean"]
    groups = list(dict.fromkeys(c.split("_")[0] for c in snr_conds))
    show = ["zero-shot", "tip-clean", "tip-aug", "lp-aug"]
    fig, axes = plt.subplots(1, len(groups), figsize=(4.2 * len(groups), 3.6), sharey=True)
    axes = np.atleast_1d(axes)
    for ax, g in zip(axes, groups):
        cs = [c for c in snr_conds if c.startswith(g + "_")]
        snrs = [int(c.split("_")[1][:-2]) for c in cs]
        order = np.argsort(snrs)[::-1]
        for m in show:
            sub = s[(s.method == m) & ((s.k == kmax) | (m == "zero-shot"))].set_index("condition")
            if sub.empty:
                continue
            xs = ["clean"] + [cs[i] for i in order]
            ax.errorbar(range(len(xs)), sub.loc[xs, "mean"], yerr=sub.loc[xs, "std"], marker="o", capsize=3,
                        label=m)
        ax.set_xticks(range(len(cs) + 1), ["clean"] + [f"{snrs[i]} dB" for i in order])
        ax.set_title(f"{g} noise" + (" (seen in cache)" if g == cfg["noise"]["aug_type"] else " (unseen)"))
        ax.grid(alpha=0.3)
    axes[0].set_ylabel(f"accuracy (%), K={kmax}")
    axes[-1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "fig1_acc_vs_snr.png", dpi=200)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=False)
    s2 = s.copy()
    s2["group"] = s2["condition"].map(lambda c: "clean" if c == "clean" else "noisy")
    agg = s2.groupby(["method", "k", "group"])["mean"].mean().reset_index()
    for ax, grp in zip(axes, ["clean", "noisy"]):
        zs = agg[(agg.method == "zero-shot") & (agg.group == grp)]["mean"]
        if len(zs):
            ax.axhline(float(zs.iloc[0]), color="gray", ls="--", label="zero-shot")
        for m in ["tip-clean", "tip-aug", "lp-clean", "lp-aug"]:
            sub = agg[(agg.method == m) & (agg.group == grp)].sort_values("k")
            ax.plot(sub.k, sub["mean"], marker="o", label=m)
        ax.set_xscale("log", base=2)
        ks = sorted(agg.loc[agg.k > 0, "k"].unique())
        ax.set_xticks(ks, [str(int(k)) for k in ks])
        ax.minorticks_off()
        ax.set_xlabel("shots per class (K)")
        ax.set_title("clean audio" if grp == "clean" else "average over 12 noisy conditions")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("accuracy (%)")
    axes[1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "fig2_acc_vs_shots.png", dpi=200)
    plt.close(fig)

    top = pc.sort_values("drop_pp", ascending=False).head(15)
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.barh(top["class"][::-1], top["zs_clean"][::-1], label="clean", color="#9ecae1")
    ax.barh(top["class"][::-1], top["zs_noisy_avg"][::-1], label="noisy avg", color="#3182bd")
    ax.set_xlabel("zero-shot accuracy (%)")
    ax.set_title("15 classes with the largest zero-shot drop under noise")
    ax.legend()
    fig.tight_layout()
    fig.savefig(fig_dir / "fig3_per_class_drop.png", dpi=200)
    plt.close(fig)
    print(f"[report] wrote {out / 'RESULTS.md'} and figures in {fig_dir}")
